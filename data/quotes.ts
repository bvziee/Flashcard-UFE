export const getQuoteForCard = (cardId: string): Quote => {
  // Use a simple hash of the card ID to deterministic selection
  let hash = 0;
  for (let i = 0; i < cardId.length; i++) {
    hash = ((hash << 5) - hash) + cardId.charCodeAt(i);
    hash |= 0; // Convert to 32bit integer
  }
  
  const absHash = Math.abs(hash);
  const quoteIndex = absHash % QUOTES_POOL.length;
  // Use a slightly different offset for author so it's not always the same author for same quote index
  const authorIndex = (absHash + quoteIndex) % AUTHORS.length;

  return {
    text: QUOTES_POOL[quoteIndex],
    author: AUTHORS[authorIndex]
  };
};
